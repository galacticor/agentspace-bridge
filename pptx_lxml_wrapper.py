def create_widescreen_prs() -> Presentation:
    """Create a 16:9 widescreen (13.333" x 7.5") Presentation."""
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    return prs


def add_blank_slide(prs: Presentation, bg_color: RGBColor = C_SURFACE):
    """Add a blank 16:9 slide with solid background."""
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    bg = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(7.5)
    )
    bg.fill.solid()
    bg.fill.fore_color.rgb = bg_color
    bg.line.fill.background()
    return slide


def zero_tf_margins(tf, wrap: bool = True, anchor=MSO_ANCHOR.TOP):
    """Fix #1: Strip default 0.1" internal text frame padding for exact Swiss grid alignment."""
    tf.margin_left = Emu(0)
    tf.margin_right = Emu(0)
    tf.margin_top = Emu(0)
    tf.margin_bottom = Emu(0)
    tf.word_wrap = wrap
    tf.vertical_anchor = anchor
    return tf


def set_cell_margins(cell, left_in=0.07, right_in=0.07, top_in=0.04, bottom_in=0.04):
    """Set tight internal padding on table cells."""
    cell.margin_left = Inches(left_in)
    cell.margin_right = Inches(right_in)
    cell.margin_top = Inches(top_in)
    cell.margin_bottom = Inches(bottom_in)


def set_cell_border(cell, side: str, color_hex: str | None, width_pt: float = 0.5):
    """
    Fix #3: 10-line lxml helper to set or clear individual table cell borders
    (`left`, `right`, `top`, `bottom`) for crisp Tufte hairline tables.
    """
    tcPr = cell._tc.get_or_add_tcPr()
    tag_map = {"left": "a:lnL", "right": "a:lnR", "top": "a:lnT", "bottom": "a:lnB"}
    tag = qn(tag_map[side])
    existing = tcPr.find(tag)
    if existing is not None:
        tcPr.remove(existing)

    ln = etree.SubElement(tcPr, tag)
    if color_hex is None:
        etree.SubElement(ln, qn("a:noFill"))
    else:
        ln.set("w", str(int(width_pt * 12700)))  # 1 pt = 12700 EMUs
        ln.set("cap", "flat")
        ln.set("cmpd", "sng")
        ln.set("algn", "ctr")
        solidFill = etree.SubElement(ln, qn("a:solidFill"))
        srgbClr = etree.SubElement(solidFill, qn("a:srgbClr"))
        srgbClr.set("val", color_hex.lstrip("#").upper())
        prstDash = etree.SubElement(ln, qn("a:prstDash"))
        prstDash.set("val", "solid")


def style_tufte_cell(
    cell,
    text: str,
    font_size: float = 9.5,
    bold: bool = False,
    color: RGBColor = C_DARK,
    bg_color: RGBColor | None = None,
    align=PP_ALIGN.LEFT,
    top_border: tuple[str | None, float] = (None, 0),
    bottom_border: tuple[str | None, float] = ("E2E8F0", 0.5),
    font_name: str = FONT_BODY,
):
    """Format a single table cell as a Tufte hairline cell with zero vertical gridlines."""
    set_cell_margins(cell, left_in=0.07, right_in=0.07, top_in=0.04, bottom_in=0.04)
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE

    if bg_color is not None:
        cell.fill.solid()
        cell.fill.fore_color.rgb = bg_color
    else:
        cell.fill.background()

    set_cell_border(cell, "left", None)
    set_cell_border(cell, "right", None)
    set_cell_border(cell, "top", top_border[0], top_border[1])
    set_cell_border(cell, "bottom", bottom_border[0], bottom_border[1])

    tf = cell.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = str(text)
    p.alignment = align
    p.font.name = font_name
    p.font.size = Pt(font_size)
    p.font.bold = bold
    p.font.color.rgb = color


def add_tufte_table(
    slide,
    x: float,
    y: float,
    w: float,
    h: float,
    headers: list[str],
    rows: list[list[str]],
    col_widths: list[float] | None = None,
    num_cols: set[int] | list[int] | None = None,
    highlight_rows: dict[int, RGBColor] | None = None,
    bold_rows: set[int] | list[int] | None = None,
    accent_cols: dict[int, RGBColor] | None = None,
    font_size: float = 9.5,
    header_bg: RGBColor = C_DARK,
    header_fg: RGBColor = C_WHITE,
):
    """Build a complete Tufte hairline table using `python-pptx` + `lxml` cell borders."""
    num_cols = set(num_cols or [])
    highlight_rows = highlight_rows or {}
    bold_rows = set(bold_rows or [])
    accent_cols = accent_cols or {}

    total_rows = 1 + len(rows)
    n_cols = len(headers)
    if not col_widths or len(col_widths) != n_cols:
        col_widths = [w / max(n_cols, 1)] * n_cols

    shape = slide.shapes.add_table(total_rows, n_cols, Inches(x), Inches(y), Inches(w), Inches(h))
    tbl = shape.table

    tblPr = tbl._tbl.tblPr
    for attr in ("bandRow", "firstRow", "lastRow", "bandCol", "firstCol", "lastCol"):
        tblPr.set(attr, "0")

    for c_idx, cw in enumerate(col_widths):
        tbl.columns[c_idx].width = Inches(cw)

    for c_idx, h_text in enumerate(headers):
        align = PP_ALIGN.RIGHT if c_idx in num_cols else PP_ALIGN.LEFT
        style_tufte_cell(
            tbl.cell(0, c_idx),
            h_text,
            font_size=font_size,
            bold=True,
            color=header_fg,
            bg_color=header_bg,
            align=align,
            top_border=("0F172A", 1.5),
            bottom_border=("0F172A", 1.5),
            font_name=FONT_HEAD,
        )

    for r_idx, r_vals in enumerate(rows):
        row_bg = highlight_rows.get(r_idx, C_WHITE if r_idx % 2 == 0 else C_SURFACE)
        is_bold_row = r_idx in bold_rows
        is_last = r_idx == len(rows) - 1
        b_color = "0F172A" if (is_bold_row or is_last) else "E2E8F0"
        b_width = 1.25 if (is_bold_row or is_last) else 0.5

        for c_idx, val in enumerate(r_vals[:n_cols]):
            align = PP_ALIGN.RIGHT if c_idx in num_cols else PP_ALIGN.LEFT
            txt_color = accent_cols.get(c_idx, C_DARK)
            c_bold = is_bold_row or (c_idx == 0) or (c_idx in accent_cols)
            style_tufte_cell(
                tbl.cell(r_idx + 1, c_idx),
                str(val),
                font_size=font_size,
                bold=c_bold,
                color=txt_color,
                bg_color=row_bg,
                align=align,
                top_border=(None, 0),
                bottom_border=(b_color, b_width),
            )
    return tbl


def add_rounded_box(
    slide,
    x: float,
    y: float,
    w: float,
    h: float,
    fill_color: RGBColor = C_SURFACE,
    border_color: RGBColor | None = C_BORDER,
    border_pt: float = 0.75,
    radius: float = 0.04,
):
    """Fix #2: Rounded rectangle with crisp 0.04 corner radius instead of default pill corners."""
    shp = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h)
    )
    shp.adjustments[0] = radius
    shp.fill.solid()
    shp.fill.fore_color.rgb = fill_color
    if border_color is not None:
        shp.line.color.rgb = border_color
        shp.line.width = Pt(border_pt)
    else:
        shp.line.fill.background()
    return shp


def add_top_accent_card(
    slide,
    x: float,
    y: float,
    w: float,
    h: float,
    accent_color: RGBColor = C_CORAL,
    bg_color: RGBColor = C_WHITE,
    border_color: RGBColor = C_BORDER,
):
    """
    Fix #4: Top-border accent card (Swiss top-rule style).
    Draws a crisp card base (#FFFFFF fill, 0.75pt #E2E8F0 border) + a 0.05" tall
    top-edge accent bar so there is zero rounded-border bleeding.
    """
    base = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h)
    )
    base.fill.solid()
    base.fill.fore_color.rgb = bg_color
    base.line.color.rgb = border_color
    base.line.width = Pt(0.75)

    top_bar = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(0.05)
    )
    top_bar.fill.solid()
    top_bar.fill.fore_color.rgb = accent_color
    top_bar.line.fill.background()
    return base, top_bar


def add_textbox(
    slide,
    x: float,
    y: float,
    w: float,
    h: float,
    text: str,
    font_size: float = 11,
    bold: bool = False,
    color: RGBColor = C_DARK,
    font_name: str = FONT_BODY,
    align=PP_ALIGN.LEFT,
):
    """Zero-margin text frame helper."""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = zero_tf_margins(tb.text_frame)
    p = tf.paragraphs[0]
    p.text = str(text)
    p.alignment = align
    p.font.name = font_name
    p.font.size = Pt(font_size)
    p.font.bold = bold
    p.font.color.rgb = color
    return tb


def add_bullet_list(
    slide,
    x: float,
    y: float,
    w: float,
    h: float,
    items: list[tuple[str, str]],
    font_size: float = 10.0,
    lead_color: RGBColor = C_DARK,
    body_color: RGBColor = C_SLATE,
    space_after_pt: float = 5.0,
):
    """Add telegraphic `Bold Lead-In: Clause` paragraphs with zero internal padding."""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = zero_tf_margins(tb.text_frame)
    for idx, (lead, body) in enumerate(items):
        p = tf.paragraphs[0] if idx == 0 else tf.add_paragraph()
        p.space_after = Pt(space_after_pt)
        r1 = p.add_run()
        r1.text = f"▪ {lead}: "
        r1.font.name = FONT_BODY
        r1.font.size = Pt(font_size)
        r1.font.bold = True
        r1.font.color.rgb = lead_color

        r2 = p.add_run()
        r2.text = str(body)
        r2.font.name = FONT_BODY
        r2.font.size = Pt(font_size)
        r2.font.bold = False
        r2.font.color.rgb = body_color
    return tb


